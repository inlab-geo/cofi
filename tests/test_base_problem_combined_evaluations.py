import pickle

import numpy as np
import pytest
import scipy.sparse

from cofi import BaseProblem
from cofi._exceptions import InvocationError


class Counter:
    """picklable joint function that counts calls"""

    def __init__(self):
        self.calls = 0

    def __call__(self, model, scale=1.0, offset=0.0):
        self.calls += 1
        m = np.asarray(model, dtype=float)
        return scale * m + offset, scale * np.eye(m.size)


@pytest.fixture
def counter():
    return Counter()


@pytest.fixture
def problem(counter):
    p = BaseProblem()
    p.set_forward_and_jacobian(counter)
    return p


def test_forward_then_jacobian_calls_once(problem, counter):
    m = np.array([1.0, 2.0])
    np.testing.assert_allclose(problem.forward(m), m)
    np.testing.assert_allclose(problem.jacobian(m), np.eye(2))
    assert counter.calls == 1


def test_jacobian_then_forward_calls_once(problem, counter):
    m = np.array([1.0, 2.0])
    problem.jacobian(m)
    problem.forward(m)
    assert counter.calls == 1


def test_forward_and_jacobian_method(problem, counter):
    f, j = problem.forward_and_jacobian(np.array([3.0]))
    problem.forward(np.array([3.0]))
    assert counter.calls == 1
    np.testing.assert_allclose(f, [3.0])


def test_cache_misses(problem, counter):
    m = np.array([1.0, 2.0])
    problem.forward(m)
    problem.forward(np.array([1.0, 3.0]))  # values
    assert counter.calls == 2
    problem.forward(np.array([[1.0, 3.0]]))  # shape
    assert counter.calls == 3
    problem.forward(np.array([1.0, 3.0], dtype=np.float32))  # dtype
    assert counter.calls == 4


def test_in_place_mutation_misses(problem, counter):
    m = np.array([1.0, 2.0])
    problem.forward(m)
    m[0] = 5.0
    np.testing.assert_allclose(problem.forward(m), [5.0, 2.0])
    assert counter.calls == 2


