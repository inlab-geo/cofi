def test_pickle_drops_cache(counter):
    p = BaseProblem()
    p.set_forward_and_jacobian(counter)
    m = np.array([1.0])
    p.forward(m)
    joint = p.forward_and_jacobian
    assert joint._cache is not None
    clone = pickle.loads(pickle.dumps(joint))
    assert clone._cache is None
    assert joint._cache is not None
    np.testing.assert_allclose(clone(m)[0], [1.0])


def test_pyfm2d_style_one_solve_per_model():
    solves = []

    def solver(model):
        solves.append(1)
        return 2 * model, np.diag(np.full(model.size, 2.0))

    obs = np.array([1.0, 1.0, 1.0])
    p = BaseProblem()
    p.set_forward_and_jacobian(solver)
    p.set_data(obs)

    def objective(m):
        return float(np.sum((obs - p.forward_and_jacobian(m)[0]) ** 2))

    def gradient(m):
        t, A = p.forward_and_jacobian(m)
        return -2 * A.T @ (obs - t)

    def hessian(m):
        return 2 * p.forward_and_jacobian(m)[1].T @ p.forward_and_jacobian(m)[1]

    m = np.array([0.1, 0.2, 0.3])
    legacy_t, legacy_A = 2 * m, np.diag(np.full(3, 2.0))
    assert objective(m) == pytest.approx(np.sum((obs - legacy_t) ** 2))
    np.testing.assert_allclose(gradient(m), -2 * legacy_A.T @ (obs - legacy_t))
    np.testing.assert_allclose(hessian(m), 2 * legacy_A.T @ legacy_A)
    assert len(solves) == 1
    objective(m + 1)
    assert len(solves) == 2


@pytest.mark.parametrize("which", ["forward", "jacobian"])
def test_clear_cache_reaches_surviving_projection(which):
    state = {"k": 1.0, "calls": 0}

    def joint(m):
        state["calls"] += 1
        return m, state["k"] * np.eye(m.size)

    p = BaseProblem()
    p.set_forward_and_jacobian(joint)
    m = np.array([1.0])
    p.forward(m)
    if which == "forward":
        p.set_forward(lambda m: m)
        survivor = p.jacobian
    else:
        p.set_jacobian(lambda m: np.eye(m.size))
        survivor = p.forward
    state["k"] = 5.0
    p.clear_evaluation_cache()
    survivor(m)
    assert state["calls"] == 2
